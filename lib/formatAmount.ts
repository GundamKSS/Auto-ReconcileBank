/**
 * ฟอร์แมตจำนวนเงินสำหรับแสดงผลทุกหน้าจอ
 *
 * เดิมฟังก์ชันนี้ถูกเขียนซ้ำเหมือนกันเป๊ะอยู่ใน component กว่า 15 ไฟล์ ทำให้เวลาต้องแก้
 * พฤติกรรมการแสดงผลต้องไล่แก้ทีละที่ และพลาดได้ง่าย
 *
 * สิ่งที่ตัวนี้ทำเพิ่มจากการเรียก toLocaleString ตรงๆ คือปัดเศษที่เล็กกว่าสตางค์ทิ้งก่อนเสมอ
 * ช่องที่แสดง "ผลต่าง" มาจากการบวกลบทศนิยมหลายร้อยรายการ ผลลัพธ์จึงมีโอกาสเหลือเศษติดลบจิ๋วๆ
 * (เช่น -0.0000000001) ซึ่ง toLocaleString จะแสดงออกมาเป็น "-0.00"
 * ฝั่งบัญชีเห็นแล้วจะสงสัยทันทีว่ายอดไม่ลงตัวจริงหรือเปล่า ทั้งที่จริงลงตัวพอดี
 * (เจอจริงที่ช่อง "ยอดเท่ากัน" ฝั่งเงินออก ตอนเลือก 98 รายการเทียบกับ 119 รายการ)
 */
export function formatAmount(n: number): string {
  const text = n.toLocaleString('en-US', { minimumFractionDigits: 2, maximumFractionDigits: 2 });
  // แก้เฉพาะ "-0.00" ตอนแสดงผลเท่านั้น ไม่ไปยุ่งกับการปัดเศษ
  // (เคยลองปัดเองด้วย Math.round(n * 100) / 100 แล้วพบว่าเปลี่ยนผลลัพธ์ของค่าครึ่งสตางค์พอดี
  //  เช่น 1.005 ได้ 1.00 แทนที่จะเป็น 1.01 เพราะ 1.005 * 100 ในภาษา JS เท่ากับ 100.49999999999999
  //  การปัดเศษของ Intl แม่นกว่า จึงปล่อยให้ Intl จัดการแล้วค่อยตัดเครื่องหมายลบของศูนย์ทิ้ง)
  return text === '-0.00' ? '0.00' : text;
}

/** เหมือน formatAmount แต่ยอมรับค่าว่างได้ — ใช้กับคอลัมน์ในรายงานที่บางแถวไม่มียอด */
export function formatAmountOrDash(n: number | null | undefined): string {
  if (n === null || n === undefined) return '-';
  return formatAmount(n);
}
