/* ---------- table helper ---------- */
function cellPara(v, o = {}) {
  const runs = (Array.isArray(v) ? v : [v]).map(x => typeof x === 'string'
    ? new TextRun({ text: x, font: FONT, size: o.size || 19, bold: o.bold, color: o.color })
    : new TextRun({ ...x, font: FONT, size: x.size || o.size || 19 }));
  return new Paragraph({ alignment: o.align || AlignmentType.LEFT, spacing: { before: 40, after: 40, line: 270 }, children: runs });
}
function TBL(headers, rows, widths, o = {}) {
  const total = widths.reduce((a, b) => a + b, 0);
  const cols = widths.map(w => Math.round(w / total * TW));
  const border = { style: BorderStyle.SINGLE, size: 4, color: 'B8C6DB' };
  const borders = { top: border, bottom: border, left: border, right: border };
  const headRow = new TableRow({
    tableHeader: true,
    children: headers.map((h, i) => new TableCell({
      width: { size: cols[i], type: WidthType.DXA },
      shading: { type: ShadingType.CLEAR, fill: LIGHT, color: 'auto' },
      margins: { top: 60, bottom: 60, left: 90, right: 90 },
      children: [cellPara(h, { bold: true, color: BLUE, size: 19 })],
    })),
  });
  const bodyRows = rows.map((r, ri) => new TableRow({
    children: r.map((c, i) => new TableCell({
      width: { size: cols[i], type: WidthType.DXA },
      shading: ri % 2 ? { type: ShadingType.CLEAR, fill: GREY, color: 'auto' } : undefined,
      margins: { top: 60, bottom: 60, left: 90, right: 90 },
      children: [cellPara(c, { size: o.size || 19, align: (o.alignCols && o.alignCols[i]) || AlignmentType.LEFT })],
    })),
  }));
  return new Table({ columnWidths: cols, width: { size: TW, type: WidthType.DXA }, borders, rows: [headRow, ...bodyRows] });
}

/* ---------- figure helper ---------- */
function FIG(file, caption, maxWidthPx = 640) {
  const { w, h } = pngSize(file);
  const width = Math.min(maxWidthPx, w);
  const height = Math.round(h * (width / w));
  return [
    new Paragraph({
      alignment: AlignmentType.CENTER, spacing: { before: 180, after: 60 },
      children: [new ImageRun({ type: 'png', data: fs.readFileSync(file), transformation: { width, height } })],
    }),
    new Paragraph({
      alignment: AlignmentType.CENTER, spacing: { before: 0, after: 220 },
      children: [new TextRun({ text: caption, font: FONT, size: 18, italics: true, color: '5A6B80' })],
    }),
  ];
}
